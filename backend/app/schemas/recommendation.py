from datetime import datetime
from typing import List, Optional, Dict, Any
from pydantic import BaseModel, Field
from app.schemas.crop import CropResponse


class RecommendationGenerateRequest(BaseModel):
    farm_id: int = Field(..., description="Target farm ID")
    season: Optional[str] = Field("Kharif (Monsoon)", description="Target growing season")
    risk_tolerance: Optional[str] = Field("balanced", description="'conservative', 'balanced', or 'high_yield'")
    monsoon_forecast_assumption: Optional[str] = Field("normal", description="'normal', 'delayed_onset', 'deficit_rainfall', 'excess_rainfall'")


class FactorScoreDetail(BaseModel):
    raw_score: Optional[float] = None
    configured_weight: float
    normalized_weight: float
    evaluated: bool
    status: str  # 'evaluated', 'missing', 'not_provided'
    explanation: str


class DataQualityInfo(BaseModel):
    completeness_percentage: float = Field(..., ge=0.0, le=100.0)
    confidence_classification: str = Field(..., description="'High' | 'Medium' | 'Low' | 'Provisional'")
    evaluated_factors: List[str]
    missing_factors: List[str]
    effective_weights: Dict[str, float]
    quality_notes: str


class ScoredCropResult(BaseModel):
    crop: CropResponse
    suitability_score: float
    risk_level: str
    confidence: str
    supporting_factors: List[str]
    climate_challenges: List[str]
    missing_factors_impact: List[str]
    data_sources: List[str]
    factor_breakdown: Dict[str, FactorScoreDetail]


class RecommendationResponse(BaseModel):
    id: int
    farm_id: int
    farm_name: str
    location_summary: str
    selected_season: str
    data_quality: DataQualityInfo
    recommended_crops: List[CropResponse]  # Contains full crop details with updated scores & risks for React frontend
    recommendation_details: List[ScoredCropResult]
    recommendation_explanation: str
    scientific_disclaimer: str = (
        "Recommendations are generated by GREENPULSE's multi-factor agronomic suitability engine. "
        "They do not guarantee harvest yield or immunity from unseasonal meteorological extremes. "
        "Consult local Krishi Vigyan Kendra (KVK) extension officers for micro-plot seed rate adjustments."
    )
    created_at: datetime

    class Config:
        from_attributes = True

